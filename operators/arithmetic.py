a = 10
b = 3

# 1. ARITHMETIC - gives a NUMBER
print("Addition:", a + b)        # 13
print("Subtraction:", a - b)     # 7
print("Multiplication:", a * b)   # 30
print("Division:", a / b)        # 3.333...
print("Floor Division:", a // b)  # 3 - only full part
print("Remainder:", a % b)       # 1 - what is left
print("Power:", a ** b)          # 1000 - 10*10*10

print("-----")